"""Generate bounded static news lists and individual stories."""
import html
import json
import re
from datetime import date
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
START, END = '<!-- NEWS_START -->', '<!-- NEWS_END -->'
GENERATED = '<!-- Generated by scripts/build_news.py -->'
PAGE_SIZE = 10
SITE = 'https://weihaochiu.github.io/'
STYLE_URL = 'assets/css/styles.css?v=news-20261023-2'


def esc(value):
    return html.escape(str(value), quote=True)


def render(items, full=False, limit=3, prefix=''):
    cards = []
    ordered = sorted(items, key=lambda row: row['sortDate'], reverse=True)
    for item in ordered[:None if full else limit]:
        anchor, title = esc(item['id']), esc(item['title'])
        url = prefix + 'news/' + item['id'] + '.html'
        body = ''.join(f'<p>{esc(p)}</p>' for p in item['paragraphs']) if full else f'<p>{esc(item["summary"])}</p>'
        image, thumbnail = item.get('image'), ''
        if full:
            for photo in ([image] if image else []) + item.get('additionalImages', []):
                body += (f'<figure class="news-photo"><a href="{esc(prefix + photo["full"])}" target="_blank" rel="noopener" aria-label="Open full-size photograph">'
                         f'<img src="{esc(prefix + photo["src"])}" width="{photo["width"]}" height="{photo["height"]}" loading="lazy" decoding="async" alt="{esc(photo["alt"])}"/></a>'
                         f'<figcaption>{esc(photo["caption"])}</figcaption></figure>')
        elif image and image.get('thumbnail'):
            thumbnail = (f'<a class="news-thumbnail" href="{esc(url)}" aria-label="Read: {title}">'
                         f'<img src="{esc(prefix + image["thumbnail"])}" width="{image["thumbnailWidth"]}" height="{image["thumbnailHeight"]}" loading="lazy" decoding="async" alt="{esc(image["alt"])}"/></a>')
        related = item.get('relatedUrl')
        if full:
            body += ''.join(f'<p class="news-source">Source: <a href="{esc(source["url"])}" target="_blank" rel="noopener">{esc(source["label"])}</a></p>' for source in item.get('sources', []))
        link = (f'<a class="action" href="{esc(prefix + related)}">View award record →</a>' if related else '') if full else f'<a class="action" href="{esc(url)}">Read news →</a>'
        level = 2 if full else 3
        heading = title if full else f'<a href="{esc(url)}">{title}</a>'
        content = f'<div class="news-copy"><p class="news-date">{esc(item["dateLabel"])}</p><h{level} id="title-{anchor}">{heading}</h{level}>{body}{link}</div>'
        cards.append(f'<article class="news-entry{" has-thumbnail" if thumbnail else ""}" id="{anchor}" aria-labelledby="title-{anchor}">{thumbnail}{content}</article>')
    return '\n'.join(cards) or '<p>No news yet.</p>'


def page_path(number, year=None):
    if year:
        return f'news/{year}' + (f'-page-{number}' if number > 1 else '') + '.html'
    return 'news.html' if number == 1 else f'news/page-{number}.html'


def relative_assets(markup, prefix):
    def replace(match):
        value = match[2]
        if not value or value.startswith(('#', '/')) or urlsplit(value).scheme:
            return match[0]
        return match[1] + prefix + value + match[3]
    return re.sub(r'((?:href|src)=")(.*?)(")', replace, markup)


def main():
    items = json.loads((ROOT / 'data/news.json').read_text(encoding='utf-8'))
    ids = [item['id'] for item in items]
    if len(ids) != len(set(ids)) or any(not re.fullmatch(r'[a-z][a-z0-9]*(?:-[a-z0-9]+)*', key) or re.fullmatch(r'page-[0-9]+', key) for key in ids):
        raise ValueError('News IDs must be unique URL-safe anchors starting with a letter')
    for item in items:
        date.fromisoformat(item['sortDate'])
        for source in item.get('sources', []):
            parsed = urlsplit(source['url'])
            if parsed.scheme != 'https' or not parsed.netloc:
                raise ValueError('News sources must use absolute HTTPS URLs')
        related = item.get('relatedUrl', '')
        if urlsplit(related).scheme or related.startswith(('/', '.')):
            raise ValueError('Related links must be site-relative paths')
    items.sort(key=lambda row: row['sortDate'], reverse=True)
    index = ROOT / 'index.html'
    text = index.read_text(encoding='utf-8')
    text = re.sub(r'href="assets/css/styles\.css(?:\?[^"]*)?"', f'href="{STYLE_URL}"', text)
    section = START + '\n<section class="content shell" id="latest-news" aria-labelledby="latest-news-title"><div class="section-title"><div><span class="kicker">Updates</span><h2 id="latest-news-title">Latest News</h2></div><a href="news.html">View all news →</a></div><div class="news-preview">' + render(items) + '</div></section>\n' + END
    if START in text:
        text = re.sub(re.escape(START) + '.*?' + re.escape(END), lambda _: section, text, flags=re.S)
    else:
        text = text.replace('    <section class="content shell" id="about">', section + '\n\n    <section class="content shell" id="about">', 1)
    count = len(json.loads((ROOT / 'data/awards.json').read_text(encoding='utf-8')))
    text = re.sub(r'(data-output-count="awards">)\d+', lambda match: match[1] + str(count), text)
    index.write_text(text, encoding='utf-8')
    template = (ROOT / 'about.html').read_text(encoding='utf-8')
    base_head = template.split('</head>')[0]
    base_head = re.sub(r'href="assets/css/styles\.css(?:\?[^"]*)?"', f'href="{STYLE_URL}"', base_head)
    header = re.search(r'<header\b.*?</header>', template, re.S).group()
    footer = re.search(r'<footer\b.*?</footer>', template, re.S).group()
    generated = {}

    def write_page(path, title, description, body, legacy=False, story=False):
        prefix = '../' if path.startswith('news/') else ''
        head = base_head.replace('About | Wei-Hao Chiu', esc(title) + ' | Wei-Hao Chiu').replace(SITE + 'about.html', SITE + path).replace('Professional experience, education, theses and awards of Wei-Hao Chiu.', esc(description))
        # Old news.html#<id> URLs continue to reach stories beyond list page one.
        redirect = '''<script>const newsId=location.hash.slice(1);if(/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(newsId)){location.replace('news/'+newsId+'.html');}</script>''' if legacy else ''
        shell = head + '</head><body>' + header + '<section class="page-header"><div class="shell"><h1>' + esc('News' if story else title) + '</h1></div></section><main class="content shell news-archive">NEWS_BODY</main>' + footer + '<script src="assets/js/app.js?v=nav-news-20261023"></script>' + redirect + '</body></html>\n'
        generated[path] = GENERATED + '\n' + relative_assets(shell, prefix).replace('NEWS_BODY', body)

    years = sorted({item['sortDate'][:4] for item in items}, reverse=True)
    for year in [None, *years]:
        selected = items if year is None else [item for item in items if item['sortDate'].startswith(year)]
        pages = max(1, (len(selected) + PAGE_SIZE - 1) // PAGE_SIZE)
        for number in range(1, pages + 1):
            path = page_path(number, year)
            prefix = '../' if path.startswith('news/') else ''
            archive_nav = '<nav class="news-years" aria-label="News archives"><a href="' + prefix + 'news.html">Latest news</a>' + ''.join(f'<a href="{prefix}news/{y}.html"' + (' aria-current="page"' if year == y else '') + f'>{y}</a>' for y in years) + '</nav>'
            navigation = '<nav class="news-pagination" aria-label="News pages">'
            if number > 1:
                navigation += f'<a href="{prefix + page_path(number-1, year)}" rel="prev">← Previous</a>'
            navigation += f'<span>Page {number} of {pages}</span>'
            if number < pages:
                navigation += f'<a href="{prefix + page_path(number+1, year)}" rel="next">Next →</a>'
            navigation += '</nav>'
            body = archive_nav + render(selected[(number-1)*PAGE_SIZE:number*PAGE_SIZE], limit=PAGE_SIZE, prefix=prefix) + navigation
            title = 'News' + (f' — {year}' if year else '') + (f' — Page {number}' if number > 1 else '')
            write_page(path, title, 'Research updates, conference activities and recognitions.', body, legacy=path == 'news.html')
    for item in items:
        path = 'news/' + item['id'] + '.html'
        body = '<a class="action" href="../news.html">← All news</a>' + render([item], full=True, prefix='../')
        write_page(path, item['title'], item['summary'], body, story=True)
    folder = ROOT / 'news'
    folder.mkdir(exist_ok=True)
    for path in folder.glob('*.html'):
        if path.relative_to(ROOT).as_posix() not in generated and path.read_text(encoding='utf-8').startswith(GENERATED):
            path.unlink()
    for path, content in generated.items():
        (ROOT / path).write_text(content, encoding='utf-8')
    return list(generated)


if __name__ == '__main__':
    main()
